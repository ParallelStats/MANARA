export const pluralCategories = ["zero", "one", "two", "few", "many", "other"] as const;
export type PluralCategory = (typeof pluralCategories)[number];

export const pluralMessageFamilies = [
  "world.cityCount",
  "fumble.count.moment",
  "fumble.count.retry",
  "fumble.count.reuse",
  "fumble.count.place",
] as const;

export type PluralMessageFamily = (typeof pluralMessageFamilies)[number];
type PluralMessageKey = `${PluralMessageFamily}.${PluralCategory}`;

type ExtractPlaceholders<Value extends string> =
  Value extends `${string}{${infer Parameter}}${infer Rest}`
    ? Parameter | ExtractPlaceholders<Rest>
    : never;

export type MessageParameters<Key extends MessageKey> = Readonly<
  Record<ExtractPlaceholders<(typeof englishMessages)[Key]>, string | number>
>;

type FormatArguments<Key extends MessageKey> =
  [ExtractPlaceholders<(typeof englishMessages)[Key]>] extends [never]
    ? readonly []
    : readonly [parameters: MessageParameters<Key>];

export function extractMessagePlaceholders(template: string): readonly string[] {
  return [...template.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/gu)]
    .map((match) => match[1])
    .filter((value): value is string => Boolean(value));
}

export function interpolateMessage(
  template: string,
  parameters: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/gu, (_, parameter: string) => {
    if (!Object.prototype.hasOwnProperty.call(parameters, parameter)) {
      throw new Error(`Missing message parameter: ${parameter}`);
    }

    return String(parameters[parameter]);
  });
}

export function formatMessage<Key extends MessageKey>(
  locale: UiLocale,
  key: Key,
  ...arguments_: FormatArguments<Key>
): string {
  const parameters = arguments_[0] as Readonly<Record<string, string | number>> | undefined;
  const template = messages[locale][key];
  return parameters ? interpolateMessage(template, parameters) : template;
}

export function selectPluralCategory(locale: UiLocale, count: number): PluralCategory {
  const category = new Intl.PluralRules(locale).select(count);
  return (pluralCategories as readonly string[]).includes(category)
    ? category as PluralCategory
    : "other";
}

export function formatPluralMessage(
  locale: UiLocale,
  family: PluralMessageFamily,
  count: number,
): string {
  if (!Number.isFinite(count)) throw new Error("Plural count must be finite.");

  const key: PluralMessageKey = `${family}.${selectPluralCategory(locale, count)}`;
  const template = messages[locale][key];
  const formattedCount = new Intl.NumberFormat(locale).format(count);
  return interpolateMessage(template, { count: formattedCount });
}

